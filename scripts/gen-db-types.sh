#!/usr/bin/env bash
#
# Regenerate the Supabase types both apps compile against, from the migrations.
#
#   scripts/gen-db-types.sh
#
# Writes the SAME file to:
#   admin/src/lib/supabase/database.types.ts
#   mobile/src/lib/database.generated.ts
#
# Why from the migrations and not from the live project: production is applied
# by hand (migrate-db.yml, workflow_dispatch only), so it can lag the repo by
# many migrations. Types generated from it describe a schema the code is not
# written against. The migrations are the schema the code expects.
#
# How: a throwaway local Supabase (database only) in a temp directory, every
# migration applied to it, then `supabase gen types --local`. Nothing here talks
# to a remote project. Needs the Supabase CLI and a running Docker runtime
# (Docker Desktop, OrbStack or `colima start`).
#
# The header stamp names the newest migration the types were built from and a
# SHA-256 of every migration's bytes; admin/src/lib/database-types.test.ts fails
# when a newer migration exists or any existing one was edited since.

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MIGRATIONS="$ROOT/admin/supabase/migrations"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/kfd-typegen.XXXXXX")"
EXCLUDE="gotrue,realtime,storage-api,imgproxy,kong,mailpit,postgrest,studio,edge-runtime,logflare,vector,supavisor"

cleanup() {
  (cd "$WORK" && supabase stop --no-backup >/dev/null 2>&1) || true
}
trap cleanup EXIT

cd "$WORK"
supabase init --force >/dev/null
# Own project id and ports, so this can run beside another local Supabase.
sed -i.bak -e 's/^project_id = .*/project_id = "kfd-typegen"/' \
  -e 's/54322/56332/;s/54320/56330/;s/54321/56331/;s/54323/56333/;s/54324/56334/;s/54327/56337/' \
  supabase/config.toml

# Same reason as scripts/db-tests.sh: the CLI runs Realtime's migrations even
# when the service is excluded, and on a fresh volume they abort the start.
sed -i.bak '/^\[realtime\]/,/^\[/s/^enabled = true/enabled = false/' supabase/config.toml
mkdir -p supabase/migrations
cp "$MIGRATIONS"/*.sql supabase/migrations/

echo "Applying $(ls "$MIGRATIONS"/*.sql | wc -l | tr -d ' ') migrations to a local database..."
supabase start -x "$EXCLUDE" >/dev/null

LATEST="$(ls "$MIGRATIONS" | grep -E '^[0-9]+_.*\.sql$' | sort | tail -1)"
# C collation so the order matches the test's plain JS sort byte for byte.
DIGEST="$(cd "$MIGRATIONS" && ls | grep -E '^[0-9]+_.*\.sql$' | LC_ALL=C sort | xargs cat | shasum -a 256 | cut -d' ' -f1)"
OUT="$WORK/database.types.ts"
{
  echo "// GENERATED by scripts/gen-db-types.sh from admin/supabase/migrations"
  echo "// through $LATEST. Do not edit by hand: rerun the script."
  echo "// migrations sha256 $DIGEST"
  echo
  supabase gen types typescript --local --schema public 2>/dev/null
} > "$OUT"

cp "$OUT" "$ROOT/admin/src/lib/supabase/database.types.ts"
cp "$OUT" "$ROOT/mobile/src/lib/database.generated.ts"
echo "Wrote types through $LATEST to admin and mobile."
